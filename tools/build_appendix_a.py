"""Generate Appendix A — the task set — from the frozen task file.

Section 3.5 says the full set is in Appendix A, and a reader who wants to
check that the tasks are what the paper claims has to be able to read all 48.

Generated rather than written by hand, from `apparatus/tasks/tasks.json` and
nothing else, so the appendix cannot drift from the file the experiment
actually ran against. The file's SHA-256 is printed at the top and is the
same hash carried on every one of the 960 data rows.

Usage:  python tools/build_appendix_a.py   # writes docs/appendix_a.md
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TASKS = ROOT / "apparatus" / "tasks" / "tasks.json"

# Category order as section 3.5 introduces them, control first.
ORDER = ["trivial", "reasoning", "action", "clarification", "grounding",
         "robustness"]

ORIGIN = {
    "frozen_v1": "predates this study, unchanged",
    "authored 2026-08-19": "written for this experiment",
    # Counted as study-written by runs/provenance_split.json, because a
    # rewrite could have been shaped by the hypotheses even though the request
    # was not. Labelled "predates this study, adapted" until 2026-09-08, which
    # made this appendix show 27 pre-existing tasks where section 7 says 22.
    "frozen_v1, rewritten 2026-08-19": "adapted for this experiment",
}


def criterion(task: dict) -> str:
    """What the task requires, in the form the scorer actually applies."""
    success = task.get("success") or {}
    kind = success.get("type", "")
    if kind == "regex":
        return f"reply matches `{success.get('pattern', '')}`"
    if kind == "contains_all":
        # `any_of` is a list of alternative required-substring sets, and a
        # reply passes if any one set is fully present -- so "5:25 pm" and
        # "17:25" are both correct without a grader deciding on the day.
        # This read `success["all"]`, a key the task file has never used,
        # until 2026-09-08; all fourteen of these rows printed the words
        # "reply contains" with nothing after them.
        groups = success.get("any_of") or []
        joined = [" and ".join(f"`{n}`" for n in group) for group in groups]
        return "reply contains " + " or ".join(joined) if joined else \
            "(no criterion recorded)"
    if kind == "rubric":
        return success.get("criteria", "") or "(no criterion recorded)"
    return f"({kind or 'unspecified'})"


def escape(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def main() -> None:
    # Written here rather than piped, because this console's default codepage
    # cannot encode the em dash or the turn separator and shell redirection
    # would corrupt them silently.
    lines: list = []

    def print(text: str = "") -> None:   # noqa: A001 - collect, do not emit
        lines.append(text)

    blob = TASKS.read_bytes()
    tasks = json.loads(blob.decode("utf-8"))
    digest = hashlib.sha256(blob).hexdigest()

    print("# Appendix A — The task set\n")
    print(f"All {len(tasks)} tasks, as run.\n")
    print("This appendix is generated by `tools/build_appendix_a.py` from "
          "`apparatus/tasks/tasks.json`\nand from nothing else, so it cannot "
          "drift from the file the experiment ran\nagainst. That file's "
          "SHA-256 is\n")
    print(f"    {digest}\n")
    print("and the same hash is carried on every one of the 960 data rows "
          "(§3.4).\n")
    print("Each task carries the request or requests put to the assistant, "
          "what counted as\nsuccess, a difficulty from 1 to 5 fixed when the "
          "task was written, and where the\ntask came from. The success "
          "criterion is reproduced as the scoring code applies\nit, which is "
          "why some read as a pattern or a list of strings rather than as a\n"
          "sentence. §3.5 describes how the set was assembled; §4.4 reports "
          "the contrast\nrecomputed on the tasks that predate this study "
          "against those written for it.\n")

    counts = {c: sum(1 for t in tasks if t["category"] == c) for c in ORDER}
    print("| category | tasks | what it is for |")
    print("|---|---|---|")
    purpose = {
        "trivial": "the control — requests both designs should handle "
                   "identically and both get right",
        "reasoning": "requests needing a conclusion drawn before acting",
        "action": "choosing and sequencing actions",
        "clarification": "requests missing a detail the assistant needs",
        "grounding": "something said earlier is needed later",
        "robustness": "requests that are malformed, impossible, or outside "
                      "what the assistant can do",
    }
    for c in ORDER:
        print(f"| {c} | {counts[c]} | {purpose[c]} |")
    print()

    for category in ORDER:
        rows = [t for t in tasks if t["category"] == category]
        print(f"\n## {category} ({len(rows)} tasks)\n")
        print("| id | difficulty | request | success criterion | origin |")
        print("|---|---|---|---|---|")
        for task in sorted(rows, key=lambda t: t["id"]):
            turns = task.get("turns") or []
            # Turns are numbered rather than separated by a glyph: the return
            # mark used before is a character Times cannot set, so the
            # renderer substituted a Japanese face for it sixteen times.
            if len(turns) > 1:
                shown = f"({len(turns)} turns) " + " ".join(
                    f"[{n}] {escape(t)}" for n, t in enumerate(turns, 1)
                )
            else:
                shown = " ".join(escape(t) for t in turns)
            print(f"| `{task['id']}` | {task.get('difficulty', '')} | "
                  f"{shown} | {escape(criterion(task))} | "
                  f"{ORIGIN.get(task.get('origin', ''), task.get('origin', ''))} |")

    multi = [t for t in tasks if len(t.get("turns") or []) > 1]
    fixtures = [t for t in tasks if t.get("fixtures")]
    print(f"\n\n{len(multi)} of the {len(tasks)} tasks run to more than one "
          f"turn, and {len(fixtures)} place\nfiles on the simulated computer "
          f"before the task begins, so that a request about a\nfile has a "
          f"file to be about.\n")
    print("The ideal decision derived for each task — whether it should ask, "
          "decline,\nbackground, or decompose, and which actions it should "
          "reach for — is not listed\nhere. It is derived from the task's "
          "own recorded properties by a rule that\n`apparatus/tasks/build.py "
          "--check` re-applies and verifies byte for byte, and\n§3.7 "
          "describes both the rule and the independent rater who re-derived "
          "every\none of them blind to the results.")

    out = ROOT / "docs" / "appendix_a.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    import sys
    sys.stderr.write(f"wrote {out.relative_to(ROOT)}, {len(lines)} lines\n")


if __name__ == "__main__":
    main()
