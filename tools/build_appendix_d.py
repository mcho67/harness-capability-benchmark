"""Generate Appendix D — the naturalness counts.

Naturalness was pre-registered as the fourth and weakest measure. The plan
also called for people to read replies blind and rate them, so that the two
automatic counts could be checked against what people actually find natural.
That never happened.

The counts are reported here anyway, and that is deliberate. A measure fixed
in the plan and then dropped from the paper because it turned out to show
nothing is selective reporting, which is the practice the whole
pre-registration exists to prevent. So it appears, in full, labelled as
supporting nothing.

Generated from the run records rather than written by hand.

Usage:  python tools/build_appendix_d.py   # writes docs/appendix_d.md
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "apparatus"))
from harness.capture import read_rows                        # noqa: E402

SCORED = ROOT / "runs" / "full-2026-08-20" / "scored.jsonl"
OUT = ROOT / "docs" / "appendix_d.md"

NAMES = {"C1": "deciding / cloud", "C2": "deciding / on-device",
         "C3": "routing / cloud", "C4": "routing / on-device"}


def main() -> None:
    frame = pd.DataFrame(read_rows(str(SCORED)))
    lines: list = []
    add = lines.append

    add("# Appendix D — Conversational naturalness\n")
    add("Naturalness was pre-registered as the fourth measure and the "
        "weakest, and §3.6\nranks it below the other three. Two things "
        "are counted in each reply: whether it\nopens with one of a list of "
        "stock phrases fixed before the run, and whether its\nlength falls "
        "inside a band set for that task when the task was written.\n")
    add("These numbers support no claim in this paper, and cannot. The "
        "plan also called\nfor people to read replies blind and rate them, so "
        "that the two counts could be\nchecked against what people actually "
        "find natural. That comparison was never made\n(Appendix C, "
        "deviation 2), so neither count has been shown to track anything a\n"
        "reader would recognize as naturalness. They are a description of the "
        "replies and\nnothing more.\n")
    add("They are reported rather than dropped because a measure named in the "
        "plan and then\nomitted from the paper, once it turned out to show "
        "nothing, is selective reporting.\n")
    add("This appendix is generated by `tools/build_appendix_d.py` from the "
        "960 scored\nruns.\n")

    add("\n## Length against the band set for each task\n")
    add(f"Counts over {len(frame) // 4} runs per configuration.\n")
    fit = pd.crosstab(frame["cell"], frame["length_fit"])
    cols = [c for c in ("under", "in_band", "over") if c in fit.columns]
    labels = {"under": "under", "in_band": "in band", "over": "over"}
    add("| configuration | " + " | ".join(labels[c] for c in cols)
        + " | share in band |")
    add("|---" * (len(cols) + 2) + "|")
    for cell in ("C1", "C2", "C3", "C4"):
        if cell not in fit.index:
            continue
        row = fit.loc[cell]
        total = int(row.sum())
        share = int(row.get("in_band", 0)) / total if total else 0.0
        add(f"| {NAMES[cell]} | "
            + " | ".join(str(int(row.get(c, 0))) for c in cols)
            + f" | {share:.3f} |")

    add("\n## Replies opening with a stock phrase\n")
    opening = frame.copy()
    opening["flag"] = opening["formulaic_opening"].astype(str).str.lower().isin(
        ("true", "1", "yes"))
    add("| configuration | stock opening | share |")
    add("|---|---|---|")
    for cell in ("C1", "C2", "C3", "C4"):
        sub = opening[opening["cell"] == cell]
        if sub.empty:
            continue
        n = int(sub["flag"].sum())
        add(f"| {NAMES[cell]} | {n} | {n / len(sub):.3f} |")

    add("\n## Reply length in words\n")
    add("| configuration | median | 90th percentile |")
    add("|---|---|---|")
    for cell in ("C1", "C2", "C3", "C4"):
        sub = pd.to_numeric(frame.loc[frame["cell"] == cell, "length_words"],
                            errors="coerce").dropna()
        if sub.empty:
            continue
        add(f"| {NAMES[cell]} | {sub.median():.0f} | {sub.quantile(0.9):.0f} |")

    add("\nNo test is run on any of the above and no interval is given, "
        "because a measure\nthat has not been validated against the thing it "
        "claims to measure does not become\nmeaningful by having a confidence "
        "interval attached to it.")

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    sys.stderr.write(f"wrote {OUT.relative_to(ROOT)}, {len(lines)} lines\n")


if __name__ == "__main__":
    main()
