"""Generate Appendix B -- the action set -- from the instrument itself.

Reads `apparatus.core.skills.actions.build_action_set()` — the same call the
two designs make when they are handed their action list — and writes
`docs/appendix_actions.md`. Nothing is typed by hand, so the appendix cannot
drift out of step with what actually ran.

The grouping matches the sentence in the paper's section 3.4: twelve act on
files, notes and timers; six report or change the machine's own state; two
store a fact and read it back; one works out arithmetic.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from apparatus.core.skills.actions import build_action_set  # noqa: E402

# The pre-registration numbers the six kinds of task (protocol section 7).
# Every action's note in the code cites one of these by number; the number is
# expanded here so the appendix can be read without the protocol to hand.
CATEGORY_NAMES = {
    1: "trivial", 2: "reasoning", 3: "action",
    4: "clarification", 5: "grounding", 6: "robustness",
}

GROUPS = [
    ("Files", ["search_files", "list_files", "read_file", "write_file",
               "delete_file", "file_stat"]),
    ("Notes", ["add_note", "show_notes", "remove_note"]),
    ("Timers", ["set_timer", "cancel_timer", "show_timers"]),
    ("The machine's own state", ["time", "date", "open_app", "close_app",
                                 "volume_up", "volume_down"]),
    ("A remembered fact", ["remember", "recall"]),
    ("Arithmetic", ["quick_math"]),
]

HEAD = """# Appendix B — The action set

An action is something the assistant can do that reaches outside the
conversation (§3.1). There are twenty-one, and both designs were given the
same twenty-one. §3.4 says the two designs differ in their loop and not in
what they can do; this is that list.

This appendix is generated by `tools/build_appendix_b.py` from
`apparatus/core/skills/actions.py`, the one file both designs read their
action list from. The description, the arguments and the last column are
reproduced as the code states them, so that wording is the code's rather than
this paper's.

Each action names in the code the category of task that required it, and the
six categories were fixed in the pre-registration before any task was written
(§3.10). The last column reproduces that note with the category number
expanded to its name. Clarification and robustness required no action of
their own, so neither appears below.

An action refuses to run when a required argument is missing, and says what
it needs instead of guessing. That is the fixed rule behind one of the two
ways either design can end up asking the user a question (§3.2); the other is
the model writing a question of its own. An argument that is accepted but not
required is shown in brackets.

The deciding design is given a twenty-second entry, `ask_user`, which puts a
question to the user and ends the turn. It reaches nothing outside the
conversation and changes nothing on the simulated computer, so it is not an
action by the definition above and is not listed below. §3.2 gives what it
does and does not change.
"""


def cell(text):
    return str(text).replace("|", r"\|")


def main():
    actions = build_action_set()
    seen = set()
    out = [HEAD]

    for title, names in GROUPS:
        out.append(f"## {title}\n")
        rows = ["| action | what it does | arguments | the category of task that required it |",
                "|---|---|---|---|"]
        for name in names:
            spec = actions[name]
            seen.add(name)
            required = list(spec.required or ())
            optional = [p for p in (spec.properties or []) if p not in required]
            args = ", ".join([f"`{a}`" for a in required]
                             + [f"[`{a}`]" for a in optional]) or "none"
            why = spec.justification
            for num, cname in CATEGORY_NAMES.items():
                why = why.replace(f"category {num}", f"the {cname} category")
            why = why.replace("protocol §7 ", "")
            rows.append(f"| `{name}` | {cell(spec.description)} | {args} | {cell(why)} |")
        out.append("\n".join(rows) + "\n")

    missing = set(actions) - seen
    if missing:
        raise SystemExit(f"actions missing from GROUPS: {sorted(missing)}")

    out.append(f"**{len(actions)} actions in total.** Generated by "
               f"`tools/build_appendix_b.py` from "
               f"`apparatus/core/skills/actions.py`.\n")

    path = ROOT / "docs" / "appendix_b.md"
    path.write_text("\n".join(out), encoding="utf-8")
    print("wrote", path, f"({len(actions)} actions)")


if __name__ == "__main__":
    main()
